def _build_url_result_rows() -> list[dict[str, Any]]:
    """作业 URL 抓取结果：报告生成时的数量口径来源（按作业版本归档）。"""
    # (作业编号, 作业版本, 抓取结果, 条数)
    spec = [
        ("CRAW-0001", 1, "成功", 8),
        ("CRAW-0001", 1, "失败", 2),
        ("CRAW-0001", 2, "成功", 10),  # 新一轮抓取，失败 URL 已更正
        ("CRAW-0001", 2, "失败", 0),
        ("CRAW-0002", 2, "成功", 6),
        ("CRAW-0002", 2, "失败", 4),
        ("CRAW-0003", 3, "成功", 9),
        ("CRAW-0003", 3, "失败", 1),
    ]
    rows: list[dict[str, Any]] = []
    next_id = 1
    for job_no, job_version, result_kind, count in spec:
        for index in range(1, count + 1):
            ok = result_kind == "成功"
            rows.append({
                "id": next_id,
                "作业编号": job_no,
                "作业版本": job_version,
                "URL": f"https://example.invalid/{job_no.lower()}/v{job_version}/{index}",
                "抓取结果": result_kind,
                "HTTP状态码": 200 if ok else 504,
                "失败原因码": None if ok else "GATEWAY_TIMEOUT",
                "采集时间": f"2026-09-0{job_version}T08:{index:02d}:00",
            })
            next_id += 1
    return rows


